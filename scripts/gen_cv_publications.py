"""Generate CV/adnan-kavak/sections/publications.tex from data/publications.json.

Usage (from the repository root):
    python3 scripts/gen_cv_publications.py

Entries are numbered in reverse (newest = highest number) per category:
J = journal articles, B = book chapters, C = conference papers.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "publications.json")
OUT = os.path.join(ROOT, "CV", "adnan-kavak", "sections", "publications.tex")

LATEX_SPECIAL = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def tex(s: str) -> str:
    s = "".join(LATEX_SPECIAL.get(c, c) for c in s)
    s = s.replace("“", "``").replace("”", "''").replace('"', "''")
    return re.sub(r"\s+", " ", s).strip()


def author(a: str) -> str:
    """'Küçük K.' -> 'K. Küçük', 'İlhan Omurca S.' -> 'S. İlhan Omurca'."""
    a = a.strip()
    if a == "et al.":
        return "et al."
    m = re.match(r"^(.*?)\s+((?:[A-ZÇĞİÖŞÜ]\.\s?)+)$", a)
    if not m:
        return tex(a)
    initials = " ".join(re.findall(r"[A-ZÇĞİÖŞÜ]\.", m.group(2)))
    full = f"{initials} {m.group(1)}"
    return r"\me{}" if full == "A. Kavak" else tex(full)


def authors(lst):
    names = [author(a) for a in lst]
    if len(names) > 1 and names[-1] != "et al.":
        return ", ".join(names[:-1]) + ", and " + names[-1] if len(names) > 2 else " and ".join(names)
    return ", ".join(names)


# Clean venues for book chapters (the AVESIS export mixes editors, pages and years).
BOOK_VENUES = {
    "Symbiotic Sensing": ("Signals and Communication Technology", "Springer", "99-118"),
    "A Novel Signaling Protocol": ("Mobile Networks and Management (MONAMI 2016), R. Agüero et al., Eds.", "Springer", ""),
    "A Method for Localization": ("Wireless Internet (WICON 2014), S. Mumtaz et al., Eds.", "Springer", "180-190"),
    "Implementation of floating point": ("Mathematical Methods in Engineering, K. Taş, J. A. Tenreiro Machado and D. Baleanu, Eds.", "Springer", "445-453"),
}


def entry(p):
    parts = [authors(p["authors"]) + ","]
    parts.append(r"\pubtitle{" + tex(p["title"]) + ",}")
    venue = p.get("venue", "")
    publisher = ""
    if p["type"] == "book":
        for k, (v, pub, pages) in BOOK_VENUES.items():
            if p["title"].startswith(k):
                venue, publisher, p = v, pub, dict(p, pages=pages)
                break
        venue = "in " + venue
    bits = [r"\pubvenue{" + tex(venue) + "}"]
    if publisher:
        bits.append(publisher)
    if p["type"] == "article":
        if p.get("volume"):
            bits.append("vol. " + tex(p["volume"]))
        if p.get("issue"):
            bits.append("no. " + tex(p["issue"]))
    if p.get("pages"):
        pg = p["pages"].strip("- ")
        bits.append(("pp. " + tex(pg).replace("-", "--")) if "-" in pg else ("art. " + tex(pg)))
    if str(p["year"]) not in venue:  # conference venues already carry their dates
        bits.append(str(p["year"]))
    line = " ".join(parts) + " " + ", ".join(bits) + "."
    if p.get("doi"):
        doi = p["doi"]
        line += r" \href{https://doi.org/" + doi.replace("%", r"\%").replace("#", r"\#") + "}{doi:" + tex(doi) + "}"
    tags = [t for t in p.get("indexing", []) if t in ("SCI-Expanded", "Scopus", "TRDizin")]
    if tags:
        line += r" \pubtag{" + " · ".join("SCI-E" if t == "SCI-Expanded" else t for t in tags) + "}"
    return line


def main():
    pubs = json.load(open(SRC, encoding="utf-8"))
    groups = [
        ("article", "J", "Journal Articles"),
        ("book", "B", "Book Chapters"),
        ("conference", "C", "Conference Papers"),
    ]
    out = [
        "%-------------------------------------------------------------------------------",
        "%\tSECTION: PUBLICATIONS (generated by scripts/gen_cv_publications.py; do not edit by hand)",
        "%-------------------------------------------------------------------------------",
        r"\cvsection{Publications}",
        "",
        r"{\fontsize{8.4pt}{11pt}\bodyfontlight\color{graytext}Complete list from AVESIS; "
        r"\textbf{A. Kavak} in bold. Indexing: SCI-E = Science Citation Index Expanded. "
        r"Full-text links: \href{https://adnankavak.github.io/publications/}{adnankavak.github.io/publications}.}\par",
        "",
    ]
    for kind, prefix, label in groups:
        items = sorted([p for p in pubs if p["type"] == kind], key=lambda p: -p["year"])
        n = len(items)
        out.append(r"\cvsubsection[" + str(n) + "]{" + label + "}")
        out.append(r"\begin{cvpubs}")
        for i, p in enumerate(items):
            out.append(r"  \pub{" + f"{prefix}{n - i}" + "}{" + entry(p) + "}")
        out.append(r"\end{cvpubs}")
        out.append("")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("wrote", OUT, {k: sum(1 for p in pubs if p["type"] == k) for k, _, _ in groups})


if __name__ == "__main__":
    main()
